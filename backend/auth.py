"""
Bharosa accounts: storage, password hashing and access tokens.
Standard library only (sqlite3, hashlib, hmac) for local use. When BHAROSA_DATABASE_URL (or DATABASE_URL)
is set, accounts are stored in PostgreSQL through psycopg instead, which serverless hosts need because
their filesystem is not persistent.
"""

import base64
import hashlib
import hmac
import json
import os
import secrets
import sqlite3
import time
from collections.abc import Iterator
from contextlib import contextmanager
from urllib.parse import parse_qsl, urlencode, urlsplit, urlunsplit

_default_db = (
    "bharosa.db"
    if not os.path.exists(os.path.join(os.path.dirname(os.path.abspath(__file__)), "atmosfusion.db"))
    or os.path.exists(os.path.join(os.path.dirname(os.path.abspath(__file__)), "bharosa.db"))
    else "atmosfusion.db"
)
DB_PATH = os.getenv(
    "BHAROSA_DB",
    os.getenv(
        "ATMOSFUSION_DB",
        os.path.join(os.path.dirname(os.path.abspath(__file__)), _default_db),
    ),
)


def _libpq_url(url: str) -> str:
    """Drops query parameters libpq rejects; the Supabase/Vercel integration adds `supa=base-pooler.x`."""
    parts = urlsplit(url)
    query = [(k, v) for k, v in parse_qsl(parts.query) if k != "supa"]
    return urlunsplit(parts._replace(query=urlencode(query)))


# POSTGRES_URL is what the Supabase and Neon integrations on Vercel inject (pooled connection)
DATABASE_URL = _libpq_url(os.getenv("BHAROSA_DATABASE_URL") or os.getenv("DATABASE_URL") or os.getenv("POSTGRES_URL") or "")
USE_POSTGRES = DATABASE_URL.startswith(("postgres://", "postgresql://"))
TOKEN_TTL_SECONDS = int(os.getenv("BHAROSA_TOKEN_TTL", os.getenv("ATMOSFUSION_TOKEN_TTL", str(7 * 24 * 3600))))  # 7 days
PBKDF2_ITERATIONS = 210_000

SCHEMA = """
CREATE TABLE IF NOT EXISTS users (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    name            TEXT    NOT NULL,
    email           TEXT    NOT NULL UNIQUE,
    password_hash   TEXT    NOT NULL,
    role            TEXT    NOT NULL DEFAULT 'forecaster',
    home_region     TEXT    NOT NULL DEFAULT 'konkan',
    lead_day        INTEGER NOT NULL DEFAULT 1,
    alert_threshold REAL    NOT NULL DEFAULT 115.6,
    theme           TEXT    NOT NULL DEFAULT 'light',
    onboarded       INTEGER NOT NULL DEFAULT 0,
    created_at      TEXT    NOT NULL
);
CREATE TABLE IF NOT EXISTS alert_acks (
    user_id   INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    alert_id  TEXT    NOT NULL,
    acked_at  TEXT    NOT NULL,
    PRIMARY KEY (user_id, alert_id)
);
CREATE TABLE IF NOT EXISTS login_failures (
    email      TEXT NOT NULL,
    failed_at  REAL NOT NULL
);
CREATE INDEX IF NOT EXISTS login_failures_email ON login_failures (email);
CREATE TABLE IF NOT EXISTS meta (
    key   TEXT PRIMARY KEY,
    value TEXT NOT NULL
);
"""
# Same tables in PostgreSQL; only the auto-increment syntax differs
PG_SCHEMA = SCHEMA.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY").replace(
    "user_id   INTEGER", "user_id   BIGINT"
).replace("REAL", "DOUBLE PRECISION") + """
-- Supabase's public API can reach tables in the public schema through its anon key. The backend's role
-- owns these tables, so it bypasses row level security; with no policies, that API gets nothing.
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE alert_acks ENABLE ROW LEVEL SECURITY;
ALTER TABLE login_failures ENABLE ROW LEVEL SECURITY;
ALTER TABLE meta ENABLE ROW LEVEL SECURITY;
"""

if USE_POSTGRES:
    import psycopg
    from psycopg.rows import dict_row

    IntegrityError: tuple[type[Exception], ...] = (sqlite3.IntegrityError, psycopg.IntegrityError)
    DatabaseUnavailable: tuple[type[Exception], ...] = (sqlite3.OperationalError, psycopg.OperationalError)
else:
    IntegrityError = (sqlite3.IntegrityError,)
    DatabaseUnavailable = (sqlite3.OperationalError,)


# ── Database ────────────────────────────────────────────────

class _PgConnection:
    """Gives psycopg the sqlite3 calls this module uses: "?" placeholders and conn.execute()."""

    def __init__(self, conn):
        self._conn = conn

    def execute(self, sql: str, params: tuple = ()):
        return self._conn.execute(sql.replace("?", "%s"), params)

    def executescript(self, sql: str) -> None:
        self._conn.execute(sql)


@contextmanager
def _connect() -> Iterator[sqlite3.Connection]:
    """One short-lived connection per call; commits on success."""
    if USE_POSTGRES:
        # prepare_threshold=None keeps it compatible with transaction-mode poolers (Supabase port 6543)
        with psycopg.connect(DATABASE_URL, row_factory=dict_row, prepare_threshold=None, connect_timeout=10) as pg:
            yield _PgConnection(pg)  # type: ignore[misc]
        return
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    try:
        yield conn
        conn.commit()
    finally:
        conn.close()


_schema_ready = False


@contextmanager
def db() -> Iterator[sqlite3.Connection]:
    """A connection with the schema guaranteed: created on first use, so it does not depend on the
    ASGI lifespan running (serverless hosts may skip it) or on the database being up at startup."""
    global _schema_ready
    with _connect() as conn:
        if not _schema_ready:
            conn.executescript(PG_SCHEMA if USE_POSTGRES else SCHEMA)
            _schema_ready = True
        yield conn


def init_db() -> None:
    with db():
        pass


def now_iso() -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())


# ── Passwords ───────────────────────────────────────────────

def hash_password(password: str) -> str:
    salt = secrets.token_bytes(16)
    digest = hashlib.pbkdf2_hmac("sha256", password.encode(), salt, PBKDF2_ITERATIONS)
    return f"pbkdf2_sha256${PBKDF2_ITERATIONS}${salt.hex()}${digest.hex()}"


def verify_password(password: str, stored: str) -> bool:
    try:
        algo, iterations, salt_hex, digest_hex = stored.split("$")
    except ValueError:
        return False
    if algo != "pbkdf2_sha256":
        return False
    digest = hashlib.pbkdf2_hmac("sha256", password.encode(), bytes.fromhex(salt_hex), int(iterations))
    return hmac.compare_digest(digest.hex(), digest_hex)


# A real hash to compare against when the email is unknown, so response time
# does not reveal whether an account exists.
_DUMMY_HASH = hash_password(secrets.token_urlsafe(12))


def check_login(email: str, password: str) -> sqlite3.Row | None:
    with db() as conn:
        row = conn.execute("SELECT * FROM users WHERE email = ?", (email,)).fetchone()
    if row is None:
        verify_password(password, _DUMMY_HASH)
        return None
    return row if verify_password(password, row["password_hash"]) else None


# ── Tokens (JWT, HS256) ─────────────────────────────────────

def _secret() -> bytes:
    env = os.getenv("BHAROSA_SECRET", os.getenv("ATMOSFUSION_SECRET"))
    if env:
        return env.encode()
    # Persist a generated secret so tokens survive backend restarts
    with db() as conn:
        row = conn.execute("SELECT value FROM meta WHERE key = 'token_secret'").fetchone()
        if row:
            return row["value"].encode()
        # Two cold-starting instances may race here; the first insert wins and both read it back
        conn.execute("INSERT INTO meta (key, value) VALUES ('token_secret', ?) ON CONFLICT (key) DO NOTHING", (secrets.token_urlsafe(48),))
        return conn.execute("SELECT value FROM meta WHERE key = 'token_secret'").fetchone()["value"].encode()


def _b64(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode()


def _unb64(text: str) -> bytes:
    return base64.urlsafe_b64decode(text + "=" * (-len(text) % 4))


def create_token(user_id: int) -> str:
    header = _b64(json.dumps({"alg": "HS256", "typ": "JWT"}, separators=(",", ":")).encode())
    now = int(time.time())
    payload = _b64(json.dumps({"sub": str(user_id), "iat": now, "exp": now + TOKEN_TTL_SECONDS}, separators=(",", ":")).encode())
    signing_input = f"{header}.{payload}".encode()
    signature = _b64(hmac.new(_secret(), signing_input, hashlib.sha256).digest())
    return f"{header}.{payload}.{signature}"


def decode_token(token: str) -> int | None:
    """Returns the user id for a valid, unexpired token, else None."""
    try:
        header, payload, signature = token.split(".")
        expected = _b64(hmac.new(_secret(), f"{header}.{payload}".encode(), hashlib.sha256).digest())
        if not hmac.compare_digest(signature, expected):
            return None
        if json.loads(_unb64(header)).get("alg") != "HS256":
            return None
        claims = json.loads(_unb64(payload))
        if int(claims["exp"]) < time.time():
            return None
        return int(claims["sub"])
    except (ValueError, KeyError, json.JSONDecodeError):
        return None


# ── Login throttling ────────────────────────────────────────
# Stored in the database, not process memory, so the limit holds across serverless instances.

_MAX_FAILURES = 5
_WINDOW_SECONDS = 300
_RETENTION_SECONDS = 24 * 3600  # longest window any key uses


def too_many_failures(key: str, limit: int = _MAX_FAILURES, window: int = _WINDOW_SECONDS) -> bool:
    """Counts recorded events for `key` within `window` seconds (login failures, or "signup:<ip>")."""
    now = time.time()
    with db() as conn:
        conn.execute("DELETE FROM login_failures WHERE failed_at < ?", (now - _RETENTION_SECONDS,))
        n = conn.execute(
            "SELECT COUNT(*) AS n FROM login_failures WHERE email = ? AND failed_at >= ?", (key, now - window)
        ).fetchone()["n"]
    return n >= limit


def record_failure(key: str) -> None:
    with db() as conn:
        conn.execute("INSERT INTO login_failures (email, failed_at) VALUES (?, ?)", (key, time.time()))


def clear_failures(key: str) -> None:
    with db() as conn:
        conn.execute("DELETE FROM login_failures WHERE email = ?", (key,))


def is_admin(user_id: int) -> bool:
    """Server-managed database IDs only; never trust a self-selected profile role."""
    ids = {x.strip() for x in os.getenv("BHAROSA_ADMIN_USER_IDS", "").split(",") if x.strip().isdigit()}
    return str(user_id) in ids
